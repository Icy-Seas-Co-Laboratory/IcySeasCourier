function invitationStatus(item) {
  if (item.revoked_at) return "revoked";
  if (new Date(item.expires_at) <= new Date()) return "expired";
  if (item.maximum_uses !== null && item.use_count >= item.maximum_uses) return "used";
  return "active";
}

