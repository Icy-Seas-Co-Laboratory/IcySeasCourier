const state = { generation: 0, token: "", expiresAt: 0, sessionLifetime: 0, lastActivity: 0, renewing: false, totpConfigured: null, setupPending: false, overview: null, projects: [], invitations: [], transfers: [], audit: [], downloadCommand: "", retrieveCommand: "", project: "", browser: null, logTransfer: "", logOffset: 0 };
const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => [...document.querySelectorAll(selector)];
const escapeHtml = (value) => String(value ?? "").replace(/[&<>'"]/g, (character) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "'": "&#39;", '"': "&quot;" })[character]);
const bytes = (value) => {
  if (!value) return "0 bytes";
  const units = ["bytes", "KB", "MB", "GB", "TB", "PB"];
  const index = Math.min(Math.floor(Math.log(value) / Math.log(1000)), units.length - 1);
  return `${(value / 1000 ** index).toLocaleString(undefined, { maximumFractionDigits: 1 })} ${units[index]}`;
};
const when = (value) => value ? new Intl.DateTimeFormat(undefined, { dateStyle: "medium", timeStyle: "short" }).format(new Date(value)) : "—";
const badge = (status) => `<span class="status ${escapeHtml(status)}">${escapeHtml(status)}</span>`;

async function api(path, options = {}) {
  const generation = state.generation;
  const response = await fetch(`/api/v1/admin${path}`, {
    cache: "no-store",
    ...options,
    headers: { "Content-Type": "application/json", "Authorization": `Bearer ${state.token}`, ...(options.headers || {}) },
  });
  if (generation !== state.generation) throw new DOMException('Session changed', 'AbortError');
  if (response.status === 401 && state.token) {
    lockConsole("Your administrator session expired. Sign in again to continue.");
  }
  if (response.status === 204) return null;
  const payload = await response.json().catch(() => ({}));
  if (generation !== state.generation) throw new DOMException('Session changed', 'AbortError');
  if (!response.ok) throw new Error(typeof payload.detail === "string" ? payload.detail : JSON.stringify(payload.detail || payload));
  return payload;
}

function lockConsole(message = "") {
  state.generation++;
  state.token = "";
  state.expiresAt = 0;
  state.sessionLifetime = 0;
  state.renewing = false;
  state.downloadCommand = "";
  state.retrieveCommand = "";
  state.invitations = [];
  $$("dialog[open]").forEach((dialog) => dialog.close());
  $("#dialog-body").replaceChildren();
  $("#detail-body").replaceChildren();
  $("#browser-entries").replaceChildren();
  $("#logs-entries").replaceChildren();
  $("#project-body").replaceChildren();
  state.browser = null; state.project = ""; state.logTransfer = "";
  $("#admin-key").value = "";
  $("#totp-code").value = "";
  $("#console").hidden = true;
  $("#login").hidden = false;
  if (message) setError(message, true);
}

function markActivity() {
  if (state.token) state.lastActivity = Date.now();
}

async function maintainAdminSession() {
  if (!state.token || state.renewing || document.hidden) return;
  const now = Date.now();
  if (now >= state.expiresAt || now - state.lastActivity >= state.sessionLifetime) {
    lockConsole("Your administrator session expired. Sign in again to continue.");
    return;
  }
  const activeRecently = now - state.lastActivity < 5 * 60 * 1000;
  const expiresSoon = state.expiresAt - now < 5 * 60 * 1000;
  if (!activeRecently || !expiresSoon) return;
  state.renewing = true;
  try {
    const session = await api("/authentication/renew", { method: "POST" });
    state.token = session.access_token;
    state.expiresAt = new Date(session.expires_at).getTime();
    state.sessionLifetime = state.expiresAt - Date.now();
  } finally {
    state.renewing = false;
  }
}

async function authentication(path, body) {
  const response = await fetch(`/api/v1/admin/authentication${path}`, {
    method: body ? "POST" : "GET",
    cache: "no-store",
    headers: { "Content-Type": "application/json" },
    body: body ? JSON.stringify(body) : undefined,
  });
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(typeof payload.detail === "string" ? payload.detail : "Authentication failed");
  return payload;
}

